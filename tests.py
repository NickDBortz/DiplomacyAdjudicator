def test_move_to_own_territory_with_convoy():
    map = get_classic_map()
    english_unit1 = add_unit('Fleet', map.north_sea, map.england)
    english_unit2 = add_unit('Army', map.yorkshire, map.england)
    english_unit3 = add_unit('Army', map.liverpool, map.england)
    german_unit1 = add_unit('Fleet', map.london, map.germany)
    german_unit2 = add_unit('Army', map.wales, map.germany)

    order1 = map.parse_order_string('F NTH C A YOR - YOR')
    order2 = map.parse_order_string('A YOR - YOR')
    order3 = map.parse_order_string('A LVP S A YOR - YOR')
    order4 = map.parse_order_string('F LON - YOR')
    order5 = map.parse_order_string('A WAL S F LON - YOR')

    english_unit1.set_order(order1)
    english_unit2.set_order(order2)
    english_unit3.set_order(order3)
    german_unit1.set_order(order4)
    german_unit2.set_order(order5)
    
    map.queue_order(order1)
    map.queue_order(order2)
    map.queue_order(order3)
    map.queue_order(order4)
    map.queue_order(order5)
    assert_equal('Map Queued orders Count', len(map.queued_orders), 3)

    map.resolve_orders()
    assert_equal('Map Queued orders Count', len(map.queued_orders), 0)

    # English army's move is illegal. This makes Liverpool's support illegal
    # This allows the Germans to have the stronger force and dislodge the army in Yorkshire
    assert_equal('English Fleet Territory', english_unit1.territory, map.north_sea)
    assert_not_equal('English Army 1 Territory', english_unit2.territory, map.yorkshire)
    assert_equal('English Army 2 Territory', english_unit3.territory, map.liverpool)
    assert_equal('German Fleet Territory', german_unit1.territory, map.yorkshire)
    assert_equal('German Army Territory', german_unit2.territory, map.wales)

